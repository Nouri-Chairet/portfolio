/**
 * Builds the responsive screenshot set for the project gallery.
 *
 * assets-src/images/<id>.png  ->  public/shots/<id>-<width>.{avif,webp}
 *
 * The gallery is a lazily-loaded chunk and these files are referenced by URL,
 * never imported, so none of this reaches the main bundle or the initial
 * payload — the browser fetches a screenshot only once the visitor opens the
 * gallery, and then only the width its viewport actually needs.
 *
 * Widths are clamped to the source: `edu` is only 600px wide, so asking for a
 * 1440 variant would just upscale and waste bytes.
 *
 * Emits src/generated/screenshots.js with the intrinsic dimensions, which the
 * gallery needs for width/height attributes — without those the lightbox
 * reflows as each image decodes.
 *
 * Usage: node scripts/generate-screenshots.mjs
 */
import sharp from 'sharp';
import { readdirSync, existsSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { join, parse } from 'node:path';

const SRC = 'assets-src/images';
const OUT_DIR = 'public/shots';
const MANIFEST = 'src/generated/screenshots.js';

/** Candidate widths; each image gets those that do not upscale it. */
const WIDTHS = [480, 960, 1440];
const QUALITY = { webp: 80, avif: 52 };

if (!existsSync(SRC)) {
  console.error(`${SRC} not found. Restore the sources first, e.g.:
  git show 7439964:public/chess.png > ${SRC}/chess.png`);
  process.exit(1);
}

mkdirSync(OUT_DIR, { recursive: true });
mkdirSync('src/generated', { recursive: true });

const files = readdirSync(SRC).filter((f) => /\.(png|jpe?g)$/i.test(f));
const manifest = {};
let totalBytes = 0;

for (const file of files) {
  const id = parse(file).name;
  const from = join(SRC, file);
  const meta = await sharp(from).metadata();

  // Never upscale. Always include the source width (capped) so the lightbox
  // has a full-quality option.
  const widths = [...new Set(WIDTHS.filter((w) => w <= meta.width).concat(
    Math.min(meta.width, WIDTHS[WIDTHS.length - 1])
  ))].sort((a, b) => a - b);

  const emitted = [];
  for (const width of widths) {
    for (const format of ['avif', 'webp']) {
      const out = join(OUT_DIR, `${id}-${width}.${format}`);
      await sharp(from)
        .resize({ width, withoutEnlargement: true })
        [format]({ quality: QUALITY[format] })
        .toFile(out);
      const bytes = statSync(out).size;
      totalBytes += bytes;
      emitted.push(`${width}.${format} ${(bytes / 1024).toFixed(0)}KB`);
    }
  }

  const largest = widths[widths.length - 1];
  manifest[id] = {
    base: `/shots/${id}`,
    widths,
    // Intrinsic size of the largest variant, for width/height attributes.
    width: largest,
    height: Math.round((meta.height / meta.width) * largest),
  };

  console.log(`${id.padEnd(7)} ${meta.width}x${meta.height} -> ${emitted.join('  ')}`);
}

writeFileSync(
  MANIFEST,
  `// GENERATED by scripts/generate-screenshots.mjs — do not edit by hand.\n` +
    `// Imported ONLY by the lazily-loaded gallery chunk, so these URLs never\n` +
    `// reach the main bundle. Run \`npm run assets:screenshots\`.\n` +
    `export default ${JSON.stringify(manifest, null, 2)};\n`
);

console.log(`\nwrote ${MANIFEST}`);
console.log(`total emitted: ${(totalBytes / 1024).toFixed(0)} KB across ${files.length} screenshots`);
